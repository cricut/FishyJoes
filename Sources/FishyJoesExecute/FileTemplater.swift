import Foundation
import swsh
import ToolchainConfig

public struct FileTemplater {
    let config: ProjectConfig
    let phasesList: [any Phases]
    let swiftPackage: SwiftPackage?
    let includeFilesNotMarkedAsGenerated: Bool
    let applyCustomizations: Bool

    let templateReplacements: [String: String]

    init(
        config: ProjectConfig,
        phasesList: [any Phases],
        swiftPackage: SwiftPackage?,
        includeFilesNotMarkedAsGenerated: Bool
    ) throws {
        self.config = config
        self.phasesList = phasesList
        self.swiftPackage = swiftPackage
        self.includeFilesNotMarkedAsGenerated = includeFilesNotMarkedAsGenerated

        // If the generation phases aren't present, the replacement list is incomplete
        // templates may contain invalid JSON/YAML, and customization shouldn't be attempted.
        self.applyCustomizations = !phasesList.isEmpty

        var replacements: [String: String] = [:]

        // MARK: generic replacements
        replacements["__MODULE_NAME__"] = config.module
        replacements["__LOWERCASE_MODULE_NAME__"] = config.module.lowercased()
        replacements["__LOWERCASE_FIRST_MODULE_NAME__"] = (config.module.first?.lowercased() ?? "") + config.module.dropFirst()
        replacements["__BINDINGS_REPO__"] = config.publishRepository

        // A template file is hand-crafted, and then it turns into a generated file, which should not be modified
        replacements["__TEMPLATE__"] = "generated"
        replacements["__TEMPLATE_CAPS__"] = "GENERATED"
        replacements["__AUTOGEN_WARNING__"] = "THIS FILE IS AUTOMATICALLY GENERATED, AND WILL BE OVERWRITTEN. DO NOT EDIT."

        // Used to template a hidden file with a non-hidden file, e.g. __DOT__gitignore
        replacements["__DOT__"] = "."

        // Collect language-specific replacements from phases
        for phases in phasesList {
            for (key, value) in try phases.generationPhaseTemplateReplacements() {
                if let oldValue = replacements[key], oldValue != value {
                    fatalError("Conflicting templates for key '\(key)':\n  \(oldValue)\n  \(value)")
                }
                replacements[key] = value
            }
        }

        // MARK: CI replacements
        replacements["__CI_RUNNER_MACOS__"] = (config.ciRunners ?? .defaults).macos
        replacements["__CI_RUNNER_UBUNTU__"] = (config.ciRunners ?? .defaults).ubuntu
        replacements["__CI_RUNNER_WINDOWS__"] = (config.ciRunners ?? .defaults).windows

        replacements["__CI_SWIFT_LINUX_TOOLCHAIN__"] = ToolVersions.shared.swiftLinux.toolchain
        replacements["__CI_SWIFT_WINDOWS_BRANCH__"] = ToolVersions.shared.swiftWindows.branch
        replacements["__CI_SWIFT_WINDOWS_BUILD__"] = ToolVersions.shared.swiftWindows.build

        let ciPreBuildHook = config.ciPreBuildHook ?? "# Build customization can be added here with the `CIPreBuildHook` key in fishy-joes.yaml"
        let preBuildHookLines = ciPreBuildHook.split(separator: "\n").map(String.init)
        replacements["__PRE_BUILD_HOOK_YAML__"] = "|" + join(lines: preBuildHookLines, indent: 10)

        let ciPostBuildHook = config.ciPostBuildHook ?? "# Post-build customization can be added here with the `CIPostBuildHook` key in fishy-joes.yaml"
        let postBuildHookLines = ciPostBuildHook.split(separator: "\n").map(String.init)
        replacements["__POST_BUILD_HOOK_YAML__"] = "|" + join(lines: postBuildHookLines, indent: 10)

        var credentialStepLines: [String] = []
        var credentialUser: String = ""
        var credentialToken: String = ""
        var ciEnv: [String: String] = [
            "FISHYJOES": "1",
            "JAVA_VERSION": "20",
            "NODE_VERSION": "18.x",
            "DOTNET_VERSION": "8.0.x",
            "GRADLE_OPTS": "-Dorg.gradle.daemon=false",
        ]

        // MARK: Package in a subdirectory of a repository publishing several packages
        // Each replacement is empty, or the unchanged text, for a package at the repository root.
        if let packagePath = config.packagePath {
            let releaseOfThisPackage = "github.event_name == 'release' && startsWith(github.event.release.tag_name, '\(config.tagPrefix)')"
            let watchedPaths = [packagePath] + config.requiredModules.compactMap { module in
                swiftPackage?.dependencyMap[module].flatMap { try? ProjectConfig.readFromFile(basePath: $0.localPath).packagePath }
            }
            replacements["__WORKFLOW_NAME_PREFIX__"] = "\(config.module) "
            replacements["__WORKFLOW_DEFAULTS__"] = "defaults:\n  run:\n    working-directory: \(packagePath)\n\n"
            replacements["__PULL_REQUEST_PATHS__"] = "\n    paths:" + watchedPaths.map { "\n      - '\($0)/**'" }.joined()
            replacements["__RELEASE_CONDITION__"] = releaseOfThisPackage
            replacements["__RELEASE_TAG_SHELL_CONDITION__"] = " && \"$RELEASE_TAG\" == \(config.tagPrefix)*"
            replacements["__STRIP_TAG_PREFIX__"] = "; VERSION=${VERSION#\(config.tagPrefix)}"
            replacements["__TAG_PREFIX__"] = config.tagPrefix
            replacements["__PACKAGE_DIR__"] = "\(packagePath)/"
            replacements["__DOWNLOAD_ARTIFACT_PATH__"] = "\n        with:\n          path: \(packagePath)"

            // The Kotlin and Dart workflows aren't triggered by releases: a release of one package would run the workflows
            // of every package. The release workflow of the repository calls them in two stages of the same run instead.
            // 'build' builds, tests and packs every package of the release, 'publish' then publishes the libraries uploaded
            // by the build stage, so a failed build of any package publishes nothing.
            replacements["__RELEASE_TRIGGER__"] = [
                "workflow_call:",
                "    inputs:",
                "      ref:",
                "        description: \"The commit to build, tagged with the release by the publish stage.\"",
                "        type: string",
                "        required: true",
                "      version:",
                "        description: \"The version of the release, without the tag prefix.\"",
                "        type: string",
                "        required: true",
                "      stage:",
                "        description: \"'build' or 'publish'.\"",
                "        type: string",
                "        required: true",
                "      local-dependencies:",
                "        description: \"The modules of the dependencies released in the same run, space separated. Their build stage has finished.\"",
                "        type: string",
                "        required: false",
                "        default: \"\"",
            ].joined(separator: "\n")
            replacements["__PUBLISH_CONDITION__"] = "inputs.stage == 'publish'"
            replacements["__RELEASE_TAG_EXPRESSION__"] = "${{ format('\(config.tagPrefix){0}', inputs.version) }}"
            replacements["__BUILD_JOB_CONDITION__"] = "\n    if: inputs.stage != 'publish'"
            // The publish stage skips the build jobs, which skips the jobs needing them unless the condition says otherwise.
            replacements["__PUBLISH_JOB_CONDITION__"] = "${{ !cancelled() && !failure() }}"
            // A called workflow runs in the concurrency context of the caller, github.workflow is the caller's name.
            replacements["__CONCURRENCY_SUFFIX__"] = "${{ inputs.stage && format('-{0}-{1}', inputs.stage, github.run_id) || '' }}"
            // The packages of a release share the artifacts of the run.
            replacements["__ARTIFACT_PREFIX__"] = "\(config.module)-"
            // The dependencies released in the same run don't have their Dart publish tags yet: the tests resolve them from
            // their directories, with the libraries their build stage uploaded (see DartPhases.useLocalDependencies()).
            replacements["__DART_LOCAL_DEPENDENCY_STEPS__"] = """
            - name: Download local dependencies
                    if: inputs.local-dependencies != ''
                    uses: actions/download-artifact@v4
                    with:
                      pattern: '*_lib'
                      path: ${{ runner.temp }}/local-dependencies

                  - name: Use local dependencies
                    if: inputs.local-dependencies != ''
                    shell: bash
                    env:
                      LOCAL_DEPENDENCIES: ${{ inputs.local-dependencies }}
                    run: |
                      echo "FISHYJOES_LOCAL_DEPENDENCIES=$LOCAL_DEPENDENCIES" >> "$GITHUB_ENV"
                      echo "FISHYJOES_LOCAL_DEPENDENCY_ARTIFACTS=$RUNNER_TEMP/local-dependencies" >> "$GITHUB_ENV"

                  
            """
            // The Kotlin builds resolve the dependencies released in the same run from the Maven local repository, which
            // comes first in the repositories of build.gradle.kts. The build stage of each package uploads its version.
            // NOTE: Gradle's Maven local repository is in the user's home, USERPROFILE on Windows.
            replacements["__KOTLIN_LOCAL_DEPENDENCY_STEPS__"] = """
            - name: Download local dependencies
                    if: inputs.local-dependencies != ''
                    uses: actions/download-artifact@v4
                    with:
                      pattern: '*-maven-local'
                      path: ${{ runner.temp }}/local-dependencies

                  - name: Install local dependencies
                    if: inputs.local-dependencies != ''
                    shell: bash
                    env:
                      LOCAL_DEPENDENCIES: ${{ inputs.local-dependencies }}
                    run: |
                      set -euxo pipefail

                      MAVEN_LOCAL="${USERPROFILE:-$HOME}/.m2/repository/com/cricut"
                      mkdir -p "$MAVEN_LOCAL"
                      for module in $LOCAL_DEPENDENCIES; do
                          rm -rf "$MAVEN_LOCAL/$module"
                          cp -R "$RUNNER_TEMP/local-dependencies/$module-maven-local" "$MAVEN_LOCAL/$module"
                      done

                  
            """
            // A runner may be persistent, the builds of other commits mustn't resolve the dependencies from there.
            replacements["__KOTLIN_LOCAL_DEPENDENCY_CLEANUP__"] = """


                  - name: Remove local dependencies
                    if: always() && inputs.local-dependencies != ''
                    shell: bash
                    env:
                      LOCAL_DEPENDENCIES: ${{ inputs.local-dependencies }}
                    run: |
                      for module in $LOCAL_DEPENDENCIES; do
                          rm -rf "${USERPROFILE:-$HOME}/.m2/repository/com/cricut/$module"
                      done
            """
            replacements["__KOTLIN_MAVEN_LOCAL_UPLOAD__"] = """
            - name: Upload Maven local repository
                    if: inputs.stage == 'build'
                    uses: actions/upload-artifact@v7
                    with:
                      name: \(config.module)-maven-local
                      path: ~/.m2/repository/com/cricut/\(config.module)
                      if-no-files-found: error

                  
            """
        } else {
            replacements["__WORKFLOW_NAME_PREFIX__"] = ""
            replacements["__WORKFLOW_DEFAULTS__"] = ""
            replacements["__PULL_REQUEST_PATHS__"] = ""
            replacements["__RELEASE_CONDITION__"] = "github.event_name == 'release'"
            replacements["__RELEASE_TAG_SHELL_CONDITION__"] = ""
            replacements["__STRIP_TAG_PREFIX__"] = ""
            replacements["__TAG_PREFIX__"] = ""
            replacements["__PACKAGE_DIR__"] = ""
            replacements["__DOWNLOAD_ARTIFACT_PATH__"] = ""
            replacements["__RELEASE_TRIGGER__"] = "release:\n    types: [published]"
            replacements["__PUBLISH_CONDITION__"] = "github.event_name == 'release'"
            replacements["__RELEASE_TAG_EXPRESSION__"] = "${{ github.event.release.tag_name }}"
            replacements["__BUILD_JOB_CONDITION__"] = ""
            replacements["__PUBLISH_JOB_CONDITION__"] = "success()"
            replacements["__CONCURRENCY_SUFFIX__"] = ""
            replacements["__ARTIFACT_PREFIX__"] = ""
            replacements["__DART_LOCAL_DEPENDENCY_STEPS__"] = ""
            replacements["__KOTLIN_LOCAL_DEPENDENCY_STEPS__"] = ""
            replacements["__KOTLIN_LOCAL_DEPENDENCY_CLEANUP__"] = ""
            replacements["__KOTLIN_MAVEN_LOCAL_UPLOAD__"] = ""
        }

        if let token = config.ciDependencyAuth?.token {
            credentialToken = token
            ciEnv["GITHUB_TOKEN"] = token
            ciEnv["NODE_AUTH_TOKEN"] = token
            ciEnv["NUGET_AUTH_TOKEN"] = token
            let userAndToken: String
            if let user = config.ciDependencyAuth?.user {
                ciEnv["GITHUB_USER"] = user
                credentialUser = user
                userAndToken = "\(user):\(token)"
            } else {
                credentialUser = ""
                userAndToken = token
            }
            credentialStepLines = [
                "- name: Setup git credentials",
                "  uses: de-vri-es/setup-git-credentials@5dd446b3857806f44ea73acf83c193190a385d63  # v2.2.0",
                "  with:",
                "    credentials: https://\(userAndToken)@github.com/",
                "",
            ]
        }
        credentialStepLines.append(
            contentsOf: [
                "- name: Checkout",
                "  uses: actions/checkout@v6",
                "  with:",
                "    submodules: recursive",
            ]
        )
        if config.packagePath != nil {
            // The commit of a release (see __RELEASE_TRIGGER__), empty for the other triggers.
            credentialStepLines.append("    ref: ${{ inputs.ref }}")
        }
        if !credentialToken.isEmpty {
            credentialStepLines.append("    token: '\(credentialToken)'")
        }
        credentialStepLines[0].removeFirst(2) // remove the first "- " so that the template can also be valid yaml
        replacements["__CI_GIT_STEPS__"] = join(lines: credentialStepLines, indent: 6).trimmed()
        replacements["__CI_DEPENDENCY_AUTH_USER__"] = credentialUser
        replacements["__CI_DEPENDENCY_AUTH_TOKEN__"] = credentialToken
        let envLines = ciEnv.sorted { $0.key < $1.key }.map { "\($0.key): '\($0.value.replacingOccurrences(of: "'", with: "''"))'" }
        replacements["__CI_SHARED_ENV_YAML__"] = join(lines: envLines, indent: 2).trimmed()

        self.templateReplacements = replacements
    }

    func installTemplate() throws {
        let templateRoot = Bundle.module.resourceURL!.appendingPathComponent("bindings-template", isDirectory: true).path
        try install(".", in: templateRoot, to: "bindings")
    }

    enum InstallBehavior {
        case skip, copy, template
        case symlink(installName: String)

        // When installing a file marked with this, FileTemplater should template first, then merge the resulting JSON or YAML file with a user customization file
        case templateAndMergeWithOverride(overridePath: String)
    }

    func installBehavior(for fileName: String, in directory: String, templateRoot: String) throws -> InstallBehavior {
        let path = "\(templateRoot)/\(directory)/\(fileName)"
        if [".DS_Store", ".gradle"].contains(fileName) {
            return .skip
        }

        if let installName = fileName.trimmingIfSuffixed(".symlink") {
            return .symlink(installName: String(installName))
        }

        // Mapping from paths of customizable files to the path of the override file
        let overridablePaths = [
            "./dart/__TEMPLATE__/pubspec.yaml": "bindings/dart/pubspec.override.yaml",
            "./dart/__TEMPLATE__/flutter-pubspec.yaml": "bindings/dart/flutter-pubspec.override.yaml",
            "./ts/__TEMPLATE__/package.wasm.json": "bindings/ts/package.override.json",
            "./ts/__TEMPLATE__/package.native-macos.json": "bindings/ts/package.override.json",
            "./ts/__TEMPLATE__/package.native-ubuntu.json": "bindings/ts/package.override.json",
            "./ts/__TEMPLATE__/package.native-windows.json": "bindings/ts/package.override.json",
            "./ts/tests/__TEMPLATE__/package.__TEMPLATE__.json": "bindings/ts/tests/package.override.json",
        ]
        if applyCustomizations, let overridePath = overridablePaths["\(directory)/\(fileName)"] {
            return .templateAndMergeWithOverride(overridePath: overridePath)
        }

        let fileType = try FileManager.default.attributesOfItem(atPath: path)[.type] as! FileAttributeType
        if
            !includeFilesNotMarkedAsGenerated,
            fileType == .typeRegular,
            path.range(of: #"\b(generated|__template__|__template_caps__)\b"#, options: [.regularExpression, .caseInsensitive]) == nil
        {
            return .skip
        }

        if fileName == "gradlew" || fileName.hasSuffix(".jar") {
            return .copy
        }

        return .template
    }

    func install(_ localSourcePath: String, in templateRoot: String, to destPath: String) throws {
        // Log.info("installing \(sourcePath) -> \(destPath)")
        let absoluteSourcePath = "\(templateRoot)/\(localSourcePath)"
        let manager = FileManager.default
        var isDirectory: ObjCBool = false
        guard manager.fileExists(atPath: absoluteSourcePath, isDirectory: &isDirectory) else {
            fatalError("Internal error. I was sure that path existed... \(absoluteSourcePath)")
        }
        if isDirectory.boolValue {
            try manager.createDirectory(atPath: destPath, withIntermediateDirectories: true)
            for sourceName in try manager.contentsOfDirectory(atPath: absoluteSourcePath) {
                let destName = processString(sourceName)
                switch try installBehavior(for: sourceName, in: localSourcePath, templateRoot: templateRoot) {
                case .skip: continue
                case .copy:
                    try cmd(
                        "cp", "-Rfp",
                        "\(absoluteSourcePath)/\(sourceName)",
                        "\(destPath)/\(destName)"
                    ).run()
                case .template:
                    try install(
                        "\(localSourcePath)/\(sourceName)",
                        in: templateRoot,
                        to: "\(destPath)/\(destName)"
                    )
                case .symlink(let installName):
                    let linkDestination = try cmd("cat", "\(absoluteSourcePath)/\(sourceName)").runString()
                    try cmd("ln", "-sfh", linkDestination, "\(destPath)/\(installName)").run()
                case .templateAndMergeWithOverride(let overridePath):
                    if FileManager.default.fileExists(atPath: overridePath) {
                        Log.info("Applying customiziations from \(overridePath) to \(destPath)/\(destName)")
                    }
                    let contents = processString(try String(contentsOfFile: "\(absoluteSourcePath)/\(sourceName)"))
                    if sourceName.hasSuffix(".json") {
                        try outputMergedJSON(
                            baseJSON: contents,
                            overridePath: overridePath,
                            overwritingFile: "\(destPath)/\(destName)"
                        )
                    } else if sourceName.hasSuffix(".yaml") {
                        try outputMergedYAML(
                            baseYAML: contents,
                            overridePath: overridePath,
                            overwritingFile: "\(destPath)/\(destName)"
                        )
                    } else {
                        fatalError("Internal error. Don't know how to apply overrides to template file '\(sourceName)'")
                    }
                }
            }
        } else {
            let contents = processString(try String(contentsOfFile: absoluteSourcePath))
            try contents.write(toFile: destPath, atomically: true, encoding: .utf8)
        }
    }

    private func outputMergedJSON(baseJSON: String, overridePath: String, overwritingFile: String) throws {
        let command: any Command
        if FileManager.default.fileExists(atPath: overridePath) {
            // Recursively merge 2 JSON files, preferring entries in the 2nd
            command = cmd("jq", "-e", "-s", ".[0] * .[1]", "-", overridePath)
        } else {
            command = cmd("cat")
        }
        try command
            .input(baseJSON)
            .output(overwritingFile: overwritingFile)
            .run()
    }

    private func outputMergedYAML(baseYAML: String, overridePath: String, overwritingFile: String) throws {
        let command: any Command
        if FileManager.default.fileExists(atPath: overridePath) {
            // Recursively merge 2 yaml files, preferring entries in the 2nd
            command = cmd("yq", "-e", "-p=yaml", "-o=yaml", #". * load("\#(overridePath)")"#)
        } else {
            command = cmd("cat")
        }
        try command
            .input(baseYAML)
            .output(overwritingFile: overwritingFile)
            .run()
    }

    // Fill in templates for both filenames and file contents
    func processString(_ input: String) -> String {
        var string = input
        for (key, replacement) in templateReplacements.sorted(by: <) {
            string = string.replacingOccurrences(of: key, with: replacement)
        }
        return string
    }
}
